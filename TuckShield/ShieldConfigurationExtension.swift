import ManagedSettings
import ManagedSettingsUI
import SwiftUI
import UIKit

class ShieldConfigurationExtension: ShieldConfigurationDataSource {
    override func configuration(shielding application: Application) -> ShieldConfiguration {
        Self.configuration()
    }

    override func configuration(shielding application: Application, in category: ActivityCategory) -> ShieldConfiguration {
        Self.configuration()
    }

    override func configuration(shielding webDomain: WebDomain) -> ShieldConfiguration {
        Self.configuration()
    }

    override func configuration(shielding webDomain: WebDomain, in category: ActivityCategory) -> ShieldConfiguration {
        Self.configuration()
    }

    // All four overloads render the same screen. The shielded app, the web domain and the category
    // are deliberately unused: naming what is blocked would turn the block screen into a list of the
    // things the user is missing, and the shield has no way to show one without the others.
    //
    // What is readable here and what is not: the quota lives in the App-Group container, which this
    // extension can only reach once the App Group is actually provisioned. When it cannot,
    // UserDefaults(suiteName:) falls back to this extension's own empty defaults and every quota
    // reads full — the shield then shows the normal copy and offers the unlock, and the app tells
    // the truth a tap later. That is the safe direction of the failure, but it is a failure, and
    // nothing here may be read as evidence that the quota shown is the real one.
    private static func configuration() -> ShieldConfiguration {
        let context = OverrideContext.current()
        let copy = ShieldCopy.content(for: context, allowance: context.quota.allowance())

        let text = UIColor(ShieldPalette.text)
        let background = UIColor(ShieldPalette.background)
        let button = UIColor(ShieldPalette.primaryButtonBackground)
        let buttonLabel = UIColor(ShieldPalette.primaryButtonLabel)
        // A pre-rendered asset, not an ImageRenderer call: the shield-configuration service calls
        // these overloads on an undocumented thread, and every ImageRenderer member is
        // MainActor-isolated — the hop this extension would need is one it cannot make safely.
        // Regenerated by tools/render-shield-mascot.sh from ShieldMascotIcon.
        let icon = UIImage(named: "ShieldMascot")

        // The only remaining reason for no second button is an exhausted quota, and there the
        // shorter initializer is the point: nothing is offered because nothing is left.
        guard let secondaryButton = copy.secondaryButton else {
            return ShieldConfiguration(
                backgroundColor: background,
                icon: icon,
                title: .init(text: copy.title, color: text),
                subtitle: .init(text: copy.subtitle, color: text),
                primaryButtonLabel: .init(text: copy.primaryButton, color: buttonLabel),
                primaryButtonBackgroundColor: button
            )
        }

        // The three items are the same three OverrideReason cases the app's own override screen
        // offers — choosing one here skips the picker there, it does not skip the timer.
        return ShieldConfiguration(
            backgroundColor: background,
            icon: icon,
            title: .init(text: copy.title, color: text),
            subtitle: .init(text: copy.subtitle, color: text),
            primaryButtonLabel: .init(text: copy.primaryButton, color: buttonLabel),
            primaryButtonBackgroundColor: button,
            // The secondary button gets no background colour from ShieldConfiguration, so it keeps
            // the charcoal-on-cream of the title and subtitle (3.96:1) rather than the button pair.
            secondaryButtonLabel: .init(text: secondaryButton, color: text),
            secondaryButtonSubmenuItems: OverrideReason.allCases.map(\.displayName)
        )
    }
}
